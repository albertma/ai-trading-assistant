def migrate():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    
    # 建表
    c.execute("""
        CREATE TABLE IF NOT EXISTS industry_chain (
            industry TEXT PRIMARY KEY,
            chain_data TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            notes TEXT DEFAULT ''
        )
    """)
    
    # 插入种子数据
    from datetime import datetime
    now = datetime.now().isoformat(timespec='seconds')
    
    for industry, chain in INDUSTRY_CHAIN_MAP.items():
        c.execute(
            "INSERT OR REPLACE INTO industry_chain (industry, chain_data, updated_at) VALUES (?, ?, ?)",
            (industry, json.dumps(chain, ensure_ascii=False), now)
        )
    
    conn.commit()
    
    # 验证
    c.execute("SELECT COUNT(*) FROM industry_chain")
    count = c.fetchone()[0]
    print(f"✅ 迁移完成：{count} 条产业链记录")
    
    # 打印所有行业名
    c.execute("SELECT industry FROM industry_chain ORDER BY industry")
    for row in c.fetchall():
        print(f"  - {row[0]}")
    
    conn.close()


if __name__ == "__main__":
    migrate()
